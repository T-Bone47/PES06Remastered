#!/usr/bin/env python3
"""
Generate remaster_manifest.txt.

Sources of truth:
  * every hardcoded game address in the adopted upstream sources
    (src/hooks/*.cpp, src/hooks/*.h) - matched against the target exe
  * the Ghidra-proven addresses we recorded ourselves

For every address we emit the value AND the first bytes of the instruction
stream, so the ASI can refuse to install a hook that does not match the build
it is running against.

Usage:
    python gen_manifest.py <pes6.exe> <src-dir> <out-manifest.txt>
"""
import re
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
# verify_addresses.py lives in the sibling PES6/tools directory.
for _cand in (Path(__file__).resolve().parent,
               Path(__file__).resolve().parent.parent.parent / "tools"):
    if (_cand / "verify_addresses.py").exists():
        sys.path.insert(0, str(_cand))
        break
from verify_addresses import PE

# Matches:  name = reinterpret_cast<FN_NAME>( 0x00XXXXXX );
#      or:  name = (FN_NAME)(0x00XXXXXX);
ADDR_RE = re.compile(
    r"\b(?P<name>[A-Za-z_]\w*)\s*=\s*"
    r"(?:reinterpret_cast\s*<\s*[^>]*?>\s*\(\s*|"
    r"\(\s*[A-Za-z_]\w*\s*\)\s*\(\s*)"
    r"(?P<addr>0x[0-9a-fA-F]{6,8})"
)

# The addresses we resolved ourselves with Ghidra, with a short note.
# A trailing False marks a data address: its contents are runtime values, so
# there is no prologue to verify and no signature should be emitted.
OWN = {
    "d3d.init": ("D3D init: writes the resolution globals", 0x00404C60, True),
    "d3d.createwindow": ("CreateWindowExA wrapper (hInst, clientW, clientH)", 0x00410C20, True),
    "tex.set_size": ("sets the texture width and height globals", 0x00874A20, True),
    "d3d.createdevice": ("reads the resolution globals, creates the device", 0x00405300, True),
    "gameplay.formation": ("formation loader", 0x0072E400, True),
    "gameplay.team_a": ("home/away team slots", 0x00752AC0, True),
    "gameplay.match_init": ("match environment bootstrap", 0x00AB6320, True),
    "afs.newfilefromafs": ("game AFS loader", 0x65B63F, True),
    "afs.newfilefromafs2": ("game AFS loader (2)", 0x8A4C36, True),
    "afs.allocatebuffers": ("AFS buffer allocation", 0x45A607, True),
    "afs.afterfilefromafs": ("AFS post-read", 0x65B668, True),
    "afs.filefromafs_jump": ("AFS file-from jump hack", 0x8B1983, True),
    "afs.unpack": ("the unzlib inflate routine - asset replacement point", 0x008CD490, True),
    "afs.unpack_cs": ("call site that invokes the inflate routine", 0x0065B176, True),
    "afs.multi_unpack": ("multi asset unpack call site", 0x008CD469, True),
    "afs.unidecode": ("filename unicode decode", 0x008CD490, True),
    "afs.readfile": ("ReadFile", 0x44C014, True),
    "afs.closehandle": ("CloseHandle", 0x44BC6C, True),
    "data.width_global": ("resolution width global", 0x00F83FD8, False),
    "data.height_global": ("resolution height global", 0x00F83FDC, False),
    "data.pp_struct": ("presentation parameters struct", 0x00F83EBC, False),
    "afs.pagelen_table": ("kitserver AFS page-length table", 0x03B5CBC0, False),
    "afs.fileinfo_base": ("kitserver fileinfo base", 0x01246860, False),
}


def main():
    exe, src_dir, out = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3])
    pe = PE(exe)
    text = next((s for s in pe.sections if s["vaddr"] == 0x1000), pe.sections[0])

    def probe(va, n=8):
        rva = va - pe.image_base
        if rva < 0:
            return None
        off = pe.rva_to_offset(rva)
        if off is None:
            return None
        return pe.data[off:off + n]

    found = {}
    for f in sorted(src_dir.rglob("*")):
        if f.suffix not in (".cpp", ".h"):
            continue
        txt = f.read_text(encoding="utf-8", errors="replace")
        for m in ADDR_RE.finditer(txt):
            name, addr = m.group("name"), int(m.group("addr"), 16)
            if not (0x00400000 <= addr < pe.image_base + pe.size_of_image):
                continue
            found.setdefault(addr, []).append((f.name, name))

    lines = []
    lines.append("# remaster manifest - GENERATED by tools/gen_manifest.py")
    lines.append("#")
    lines.append("# Target : %s" % Path(exe).name)
    lines.append("# sha256 : %s" % pe.sha256())
    lines.append("# image  : 0x%08X" % pe.image_base)
    lines.append("#")
    lines.append("# Every entry carries the first bytes of the target's instruction")
    lines.append("# stream. The ASI verifies them before installing a hook, so a")
    lines.append("# mismatched build degrades to a disabled feature instead of a crash.")
    lines.append("")
    lines.append("# --- our own hooks ----------------------------------------------------")
    for key, (note, addr, is_code) in OWN.items():
        b = probe(addr) if is_code else None
        if b is None:
            lines.append("%-24s = 0x%08X   # %s%s" % (
                key, addr, note, "" if is_code else "  (data address)"))
            continue
        lines.append("%-24s = 0x%08X" % (key, addr))
        lines.append("%-24s   # %s" % ("", note))
        lines.append("sig.%-23s = %s" % (key, " ".join("%02X" % x for x in b)))
    lines.append("")
    lines.append("# --- upstream gameplay hooks (from src/hooks) ------------------------")
    for addr in sorted(found):
        names = sorted({n for _, n in found[addr]})
        key = "game." + names[0].lower()
        b = probe(addr)
        if b is None:
            continue
        lines.append("%-24s = 0x%08X   # %s" % (key, addr, ", ".join(names[:3])))
        lines.append("sig.%-23s = %s" % (key, " ".join("%02X" % x for x in b)))
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote %s" % out)
    print("  own entries      : %d" % len(OWN))
    print("  upstream hooks   : %d distinct addresses" % len(found))
    unmapped = [a for a in found if probe(a) is None]
    if unmapped:
        print("  NOT MAPPED       : %d -> %s" % (
            len(unmapped), ", ".join("0x%08X" % a for a in unmapped[:8])))


if __name__ == "__main__":
    main()

